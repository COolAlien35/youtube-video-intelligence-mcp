"""Generate docs/policy/gate_status.md from the configured policy gates."""

from __future__ import annotations

from pathlib import Path

from yt_intel.config import get_settings
from yt_intel.policy.ledger import GateId, evidence_reference

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/policy/gate_status.md"

_GATE_SPEC: dict[GateId, tuple[str, str]] = {
    GateId.POL_01: ("Derived video discovery (`FR-1`)", "Written determination & audit for derived rankings"),
    GateId.POL_02: ("Derived channel discovery (`FR-2`)", "Written determination & audit for derived channel similarity"),
    GateId.POL_03: ("Derived engagement & recommendations (`FR-3`/`FR-4`)", "Written determination & audit for derived analytics"),
    GateId.POL_04: ("Account OAuth & write scope (`FR-3`–`FR-5`)", "Consented account data use & scope approval"),
    GateId.POL_05: ("Compliance ledger & account scope (`FR-3`–`FR-5`)", "Accepted compliance journal & deletion controls"),
    GateId.POL_06: ("Cross-owner aggregation", "Written cross-owner scoring permission or exception"),
    GateId.POL_07: ("Presentation & attribution", "Verified YouTube branding, canonical links & educational value"),
    GateId.POL_08: ("Remote MCP service", "Written YouTube API Services determination for remote MCP"),
}


def render_gate_status(settings: object) -> str:
    """Render Markdown table of POL-01..POL-08 status from *settings*."""
    lines = [
        "# Policy Gate Status",
        "",
        "Generated by `scripts/policy_status.py`. Live YouTube access remains **disabled** (`YT_INTEL_LIVE_YOUTUBE_ENABLED=false`, `YT_INTEL_PLAYLIST_WRITES_ENABLED=false`) until written determinations clear.",
        "",
        "| Gate | Capability | Required SRS Evidence | Status | Evidence Reference |",
        "|---|---|---|---|---|",
    ]
    for gate in GateId:
        prefix = gate.name.lower()
        enabled = getattr(settings, f"{prefix}_open", False) is True
        ev = evidence_reference(getattr(settings, f"{prefix}_evidence", None))
        status = "open" if (enabled and ev is not None) else "closed"
        ev_cell = ev if (ev is not None and enabled) else "none"
        capability, req = _GATE_SPEC[gate]
        lines.append(f"| `{gate.value}` | {capability} | {req} | `{status}` | {ev_cell} |")
    lines.append("")
    return "\n".join(lines)


def write_gate_status(settings: object | None = None, output: Path = OUTPUT) -> Path:
    cfg = get_settings() if settings is None else settings
    output.write_text(render_gate_status(cfg), encoding="utf8")
    return output


def main() -> int:
    write_gate_status()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
